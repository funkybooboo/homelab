#!/usr/bin/env bash
# opnsense.sh -- thin CLI over the OPNsense RESTCONF API, so the operator (or a directed assistant)
# (and later the oxlorg.opnsense collection at v5) can operate the
# router from debbie without touching the web UI.
#
# Credentials live in local/opnsense-api.env (gitignored, chmod 600).
# OPNsense 25.7 keypair creation (verified against the 25.7 source):
#   System > Access > Users -> the per-row command icon on the nate
#   row ("Create and download API key for this user", ticket-style)
#   -> confirm -> downloads <hostname>_<user>_apikey.txt (key=... /
#   secret=... lines). Then:
#
# Usage:
#   scripts/opnsense.sh --import ~/Downloads/opnsense_agent_apikey.txt
#                                   # parse the downloaded keypair into
#                                   # local/opnsense-api.env (chmod 600)
#                                   # and sanity-check the connection
#   scripts/opnsense.sh status                 # whoami-ish sanity call
#   scripts/opnsense.sh GET  core/system/status
#   scripts/opnsense.sh GET  kea/leases4/search # find freshly booted nodes
#                                   # (25.7 runs Kea DHCP, not ISC dhcpd --
#                                   # the old dhcpd/leases path is gone)
#   scripts/opnsense.sh GET  routes/search
#   scripts/opnsense.sh POST interfaces/apply   # (example) trigger apply
# Paths are the API paths AFTER /api/. Output is pretty-printed JSON.
# Plan B if a keypair can't be made: OPNSENSE_USER + OPNSENSE_PASS in
# the env file ride the same Basic auth (keypair is preferred:
# revocable without touching the user's password).
#
# Read-only calls are safe; POST calls change live router state --
# they stay in the human-gated category (identity rule 2) and the
# helper prints what it is about to send before sending it.

set -euo pipefail

REPO="$(cd "$(dirname "$0")/.." && pwd)"
ENV_FILE="$REPO/local/opnsense-api.env"
MODE="${1:-status}"

# --import runs BEFORE the credential check -- it is what creates the
# credential file -- and then re-execs itself for the sanity call.
if [ "$MODE" = "--import" ]; then
  FILE="${2:?--import needs the downloaded keypair txt file}"
  [ -f "$FILE" ] || { echo "no such file: $FILE" >&2; exit 1; }
  KEY="$(grep -iE 'key' "$FILE" | grep -oiE '[A-Za-z0-9+/_-]{20,}' | head -1 || true)"
  SECRET="$(grep -iE 'secret' "$FILE" | grep -oiE '[A-Za-z0-9+/_-]{20,}' | head -1 || true)"
  [ -n "$KEY" ] && [ -n "$SECRET" ] \
    || { echo "could not find key + secret in $FILE" >&2
         echo "expected 'API key: ...'/'API secret: ...' or 'key=...'/'secret=...' lines" >&2
         exit 1; }
  cat > "$ENV_FILE" <<EOF
# generated by scripts/opnsense.sh --import $(date +%Y-%m-%d)
OPNSENSE_HOST=192.168.1.1
OPNSENSE_KEY=$KEY
OPNSENSE_SECRET=$SECRET
EOF
  chmod 600 "$ENV_FILE"
  echo "wrote $ENV_FILE (chmod 600). sanity check:"
  exec "$0" status
fi

# everything below needs credentials
[ -f "$ENV_FILE" ] || { echo "no local/opnsense-api.env -- run:" >&2
  echo "  scripts/opnsense.sh --import <downloaded apikey txt>" >&2
  echo "or copy local/opnsense-api.env.example and fill it in" >&2; exit 1; }
# shellcheck disable=SC1090
source "$ENV_FILE"
: "${OPNSENSE_HOST:?OPNSENSE_HOST missing}"
if [ -n "${OPNSENSE_USER:-}" ] && [ -n "${OPNSENSE_PASS:-}" ]; then
  AUTH="$OPNSENSE_USER:$OPNSENSE_PASS"      # plan B: basic auth
else
  : "${OPNSENSE_KEY:?OPNSENSE_KEY missing} ${OPNSENSE_SECRET:?OPNSENSE_SECRET missing}"
  AUTH="$OPNSENSE_KEY:$OPNSENSE_SECRET"
fi

api() { # api METHOD PATH [JSON_BODY]
  local method="$1" path="$2" body="${3:-}"
  local url="https://${OPNSENSE_HOST}/api/${path}"
  echo "--> $method $url${body:+ (body: $body)}" >&2
  # a bodyless GET with
  # Content-Type: application/json makes OPNsense parse the empty
  # body -> 400 "Invalid JSON syntax". Only send the header WITH a
  # body.
  if [ -n "$body" ]; then
    curl -sk -u "$AUTH" -H 'Content-Type: application/json' \
      -X "$method" -d "$body" "$url"
  else
    curl -sk -u "$AUTH" -X "$method" "$url"
  fi
  echo >&2
}

case "$MODE" in
status) api GET core/system/status | jq . ;;
GET)  api GET "$2" | jq . ;;
POST) api POST "$2" "${3:-}" | jq . ;;
*)    echo "usage: opnsense.sh [--import <txt>] | status | GET <path> | POST <path> [json-body]" >&2; exit 1 ;;
esac
